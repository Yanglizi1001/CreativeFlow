const { app, BrowserWindow } = require('electron');
const fs = require('fs');
const path = require('path');
app.disableHardwareAcceleration();

app.whenReady().then(async () => {
  const win = new BrowserWindow({ width: 1440, height: 900, show: false, frame: false, webPreferences: { contextIsolation: true, backgroundThrottling: false } });
  await win.loadFile(path.join(__dirname, '..', 'dist', 'index.html'));
  await win.webContents.insertCSS('.calendar-drawer,.context-drawer{animation:none!important}');
  await new Promise(resolve => setTimeout(resolve, 500));
  await win.webContents.executeJavaScript(`document.querySelector('.project-main-row')?.click()`);
  await new Promise(resolve => setTimeout(resolve, 450));
  await win.webContents.executeJavaScript(`document.querySelector('.task-table-row')?.click()`);
  await new Promise(resolve => setTimeout(resolve, 250));
  const project = await win.capturePage({ x: 0, y: 0, width: 1440, height: 900 });
  fs.writeFileSync(path.join(__dirname, '..', 'design', 'implementation-round2-project-list-v1.png'), project.toPNG());
  await win.webContents.executeJavaScript(`document.querySelector('.task-table-row')?.dispatchEvent(new MouseEvent('dblclick', { bubbles: true }))`);
  await new Promise(resolve => setTimeout(resolve, 250));
  await win.webContents.executeJavaScript(`Array.from(document.querySelectorAll('button')).find(button => button.textContent.trim() === '删除版本')?.click()`);
  await new Promise(resolve => setTimeout(resolve, 150));
  const deleteVersion = await win.capturePage({ x: 0, y: 0, width: 1440, height: 900 });
  fs.writeFileSync(path.join(__dirname, '..', 'design', 'implementation-version-delete-v1.png'), deleteVersion.toPNG());
  await win.webContents.executeJavaScript(`Array.from(document.querySelectorAll('.navrail button')).find(button => button.textContent.includes('审阅'))?.click()`);
  await new Promise(resolve => setTimeout(resolve, 350));
  await win.webContents.executeJavaScript(`document.querySelector('.review-row')?.click()`);
  await new Promise(resolve => setTimeout(resolve, 200));
  const center = await win.capturePage({ x: 0, y: 0, width: 1440, height: 900 });
  fs.writeFileSync(path.join(__dirname, '..', 'design', 'implementation-round2-review-center-v1.png'), center.toPNG());
  await win.webContents.executeJavaScript(`document.querySelector('.review-action .button')?.click()`);
  await new Promise(resolve => setTimeout(resolve, 350));
  const workspace = await win.capturePage({ x: 0, y: 0, width: 1440, height: 900 });
  fs.writeFileSync(path.join(__dirname, '..', 'design', 'implementation-round2-review-workspace-v1.png'), workspace.toPNG());
  await win.webContents.executeJavaScript(`Array.from(document.querySelectorAll('.navrail button')).find(button => button.textContent.includes('日历'))?.click()`);
  await new Promise(resolve => setTimeout(resolve, 250));
  await win.webContents.executeJavaScript(`document.querySelectorAll('.month-grid > div')[24]?.click()`);
  await new Promise(resolve => setTimeout(resolve, 500));
  const calendar = await win.capturePage({ x: 0, y: 0, width: 1440, height: 900 });
  fs.writeFileSync(path.join(__dirname, '..', 'design', 'implementation-round2-calendar-drawer-v1.png'), calendar.toPNG());
  app.quit();
});
